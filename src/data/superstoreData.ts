/**
 * Formats large dollar values into exact M / K notation matching the visual reference
 * e.g. 12580000 -> "12.58M", 99880 -> "99.88K", 2289560 -> "2.29M"
 */
export function formatCompactCurrency(value: number, decimals = 2): string {
  if (value >= 1_000_000) {
    const m = value / 1_000_000;
    const formatted = Number(m.toFixed(decimals)).toString();
    return `${formatted}M`;
  }
  if (value >= 1_000) {
    const k = value / 1_000;
    const formatted = Number(k.toFixed(decimals)).toString();
    return `${formatted}K`;
  }
  return value.toFixed(0);
}
